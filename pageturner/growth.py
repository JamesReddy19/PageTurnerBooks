"""Month-over-month growth report built on SQL window functions (req 74).

Every other report in this project sums a date range and stops.  That answers
"how much did we sell", not "is it growing", and the difference cannot be
computed row-by-row without either a self-join per month or a loop in Python.
Window functions express it directly in one pass:

``LAG(revenue) OVER (ORDER BY month)``
    the previous month's revenue on the same row, which is what makes a
    month-over-month comparison possible at all;
``SUM(revenue) OVER (... ROWS UNBOUNDED PRECEDING)``
    the running total, i.e. cumulative revenue up to and including this month;
``AVG(revenue) OVER (... ROWS BETWEEN 2 PRECEDING AND CURRENT ROW)``
    a three-month rolling average, which flattens one-off spikes.

Two deliberate decisions:

*The month series is generated by SQLite, then zero-filled.*  A plain
``GROUP BY`` returns only months that contain an order, so after a quiet month
``LAG`` would compare April with February and report a "growth" that silently
skips a month.  The recursive CTE below produces every calendar month in the
window and the aggregate is LEFT JOINed onto it, so ``LAG`` always means the
previous *calendar* month and a gap is honestly reported as zero.

*Growth from zero is not a percentage.*  Going from 0 to 500 paise is not
"infinity percent" and not "100%"; it is undefined, so ``growth_percent`` is
``None`` for that row and for the first month (which has no predecessor) and the
template prints a dash.  Money stays integer paise throughout; only the ratio
is a ``Decimal``, rounded half-up to one decimal place.
"""

from datetime import date
from decimal import Decimal, ROUND_HALF_UP

# A year of months is the useful default and keeps the recursive CTE small.
DEFAULT_MONTHS = 12
MAX_MONTHS = 24

# Cancelled orders are excluded everywhere else in reporting, so a growth
# figure built on them would disagree with /admin/reports for the same month.
_EXCLUDED_STATUS = "Cancelled"


def _shift_month(year, month, delta):
    """Return (year, month) ``delta`` calendar months away from (year, month)."""
    absolute = (year * 12) + (month - 1) + delta
    return absolute // 12, (absolute % 12) + 1


def month_window(months=DEFAULT_MONTHS, today=None):
    """Return the inclusive month bounds as ``YYYY-MM`` strings.

    ``months`` counts backwards from the current month, so 12 means "this month
    and the eleven before it".
    """
    months = max(1, min(int(months), MAX_MONTHS))
    today = today or date.today()
    start_year, start_month = _shift_month(today.year, today.month, -(months - 1))
    return f"{start_year:04d}-{start_month:02d}", f"{today.year:04d}-{today.month:02d}"


def _query(connection, start_month, end_month):
    """Run the window-function query.

    The ``WHERE`` is expressed as a half-open range on the month prefix rather
    than two ``date()`` comparisons: ``strftime('%Y-%m', ...)`` on the column
    then matches ``BETWEEN`` exactly, so an order at 23:59 on the last day of the
    window is included and the boundary is the same one the CTE generates.
    """
    return connection.execute(
        """
        WITH RECURSIVE months(month) AS (
            SELECT ?
            UNION ALL
            SELECT strftime('%Y-%m', date(month || '-01', '+1 month'))
            FROM months
            WHERE month < ?
        ),
        monthly AS (
            SELECT strftime('%Y-%m', o.date) AS month,
                   COUNT(*) AS orders,
                   COALESCE(SUM(o.total_paise), 0) AS revenue
            FROM orders o
            WHERE o.status != ?
              AND strftime('%Y-%m', o.date) BETWEEN ? AND ?
            GROUP BY strftime('%Y-%m', o.date)
        )
        SELECT m.month AS month,
               COALESCE(mo.orders, 0) AS orders,
               COALESCE(mo.revenue, 0) AS revenue,
               LAG(COALESCE(mo.revenue, 0)) OVER (ORDER BY m.month) AS previous_revenue,
               SUM(COALESCE(mo.revenue, 0)) OVER (
                   ORDER BY m.month ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
               ) AS running_revenue,
               CAST(ROUND(AVG(COALESCE(mo.revenue, 0)) OVER (
                   ORDER BY m.month ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
               )) AS INTEGER) AS rolling_three_revenue
        FROM months m
        LEFT JOIN monthly mo ON mo.month = m.month
        ORDER BY m.month
        """,
        (start_month, end_month, _EXCLUDED_STATUS, start_month, end_month),
    ).fetchall()


def _growth_percent(previous, current):
    """Percentage change, or ``None`` when it has no meaning."""
    if previous is None:
        return None

    previous = int(previous)

    if previous == 0:
        # Growth from nothing is undefined, not enormous.
        return None

    return (
        Decimal(int(current) - previous) * 100 / Decimal(previous)
    ).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)


def _month_label(month):
    """``2025-03`` -> ``Mar 2025``."""
    year, number = month.split("-")
    names = (
        "Jan", "Feb", "Mar", "Apr", "May", "Jun",
        "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    )
    return f"{names[int(number) - 1]} {year}"


def monthly_growth(connection, months=DEFAULT_MONTHS, today=None):
    """Return the growth report rows, newest last.

    Each row carries the raw integers the database produced plus the derived
    figures used for display, so a test can hand-check any single number against
    the order-level CSV export rather than trusting the page.
    """
    start_month, end_month = month_window(months, today=today)
    rows = []

    for row in _query(connection, start_month, end_month):
        previous = row["previous_revenue"]
        revenue = int(row["revenue"])

        rows.append(
            {
                "month": row["month"],
                "label": _month_label(row["month"]),
                "orders": int(row["orders"]),
                "revenue": revenue,
                "previous_revenue": None if previous is None else int(previous),
                "change_paise": None if previous is None else revenue - int(previous),
                "growth_percent": _growth_percent(previous, revenue),
                "running_revenue": int(row["running_revenue"]),
                "rolling_three_revenue": int(row["rolling_three_revenue"]),
            }
        )

    return rows


def summary(rows):
    """Totals shown above the table (computed from the same rows, not re-queried)."""
    total = sum(row["revenue"] for row in rows)
    orders = sum(row["orders"] for row in rows)
    with_growth = [row for row in rows if row["growth_percent"] is not None]

    best = None
    if rows:
        peak = max(rows, key=lambda row: row["revenue"])
        if peak["revenue"] > 0:
            best = peak

    return {
        "months": len(rows),
        "orders": orders,
        "revenue": total,
        "average_per_month": total // len(rows) if rows else 0,
        "best_month": best,
        "comparable_months": len(with_growth),
    }
